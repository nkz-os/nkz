#!/usr/bin/env python3
"""Generate the per-role ownership migration from an owner map.

Input: a YAML owner map (roles.<role>.{owns,reads,writes}, other_databases,
caggs, postgis_untouched) plus the catalog export (schema.name|relkind|…) that
says what kind of object each name is. Output: explicit, re-runnable SQL.

    gen_db_roles_migration.py owners.yaml catalog.psv > 106_db_roles_and_ownership.sql

The owner of a table skips ENABLE row-level security but not FORCE, which is
the whole point: core keeps its rows after the switch, and FORCE becomes the
per-table ratchet. Module roles own only their tables; anything else they
touch is an explicit transition grant that a later API replaces.
"""

from __future__ import annotations

import sys

BASE_ATTRS = "LOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOINHERIT"
EXTRA_ROLES = {
    "nkz_provisioner": "LOGIN NOSUPERUSER NOBYPASSRLS CREATEDB CREATEROLE NOINHERIT",
    "keycloak": BASE_ATTRS,
}
MAIN_DB = "nekazari"
VIEWS = {
    "public.module_tenant_plan": (
        "SELECT tenant_id, plan_level, plan_type, status, expires_at FROM public.tenants"
    ),
    "public.module_installations": (
        "SELECT module_id, tenant_id, is_enabled, installed_at FROM public.tenant_installed_modules"
    ),
}
OWNER_STMT = {"r": "ALTER TABLE IF EXISTS", "p": "ALTER TABLE IF EXISTS", "S": "ALTER SEQUENCE IF EXISTS",
              "v": "ALTER VIEW IF EXISTS", "m": "ALTER MATERIALIZED VIEW IF EXISTS"}


def _role_block(role: str, attrs: str) -> str:
    return (
        "DO $$ BEGIN\n"
        f"  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{role}') THEN\n"
        f"    CREATE ROLE {role} {attrs};\n"
        "  END IF;\n"
        "END $$;"
    )


def _schemas(names: list[str]) -> list[str]:
    return sorted({n.split(".")[0] for n in names if "." in n})


def generate(data: dict) -> str:
    roles = data["roles"]
    catalog = data.get("catalog", {})
    caggs = set(data.get("caggs", []))
    module_roles = sorted(r for r in roles if r.startswith("nkz_module_"))
    out: list[str] = []
    out.append("-- Migration 106: application roles own their objects; the superuser is for migrations only.")
    out.append("-- Generated by config/timescaledb/scripts/gen_db_roles_migration.py; re-runnable.")
    out.append("")
    out.append("-- roles")
    for role in sorted(roles):
        out.append(_role_block(role, BASE_ATTRS))
    for role, attrs in EXTRA_ROLES.items():
        out.append(_role_block(role, attrs))
    out.append("")
    out.append("-- connect")
    out.append(f"REVOKE CONNECT ON DATABASE {MAIN_DB} FROM PUBLIC;")
    out.append(f"GRANT CONNECT ON DATABASE {MAIN_DB} TO {', '.join(sorted(roles))};")
    for db, role in sorted(data.get("other_databases", {}).items()):
        if "*" in db or "<" in role:
            continue  # per-instance databases are handled where they are created
        out.append(
            "DO $$ BEGIN\n"
            f"  IF EXISTS (SELECT 1 FROM pg_database WHERE datname = '{db}')\n"
            f"     AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{role}') THEN\n"
            f"    EXECUTE 'REVOKE CONNECT ON DATABASE {db} FROM PUBLIC';\n"
            f"    EXECUTE 'GRANT CONNECT ON DATABASE {db} TO {role}';\n"
            "  END IF;\n"
            "END $$;"
        )
    out.append("")
    out.append("-- schemas")
    core_schemas = _schemas(roles["nkz_core"]["owns"]) or ["public"]
    out.append(f"GRANT USAGE, CREATE ON SCHEMA {', '.join(core_schemas)} TO nkz_core;")
    for role in module_roles:
        touched = _schemas(roles[role]["owns"] + roles[role]["reads"] + roles[role]["writes"])
        if touched:
            out.append(f"GRANT USAGE ON SCHEMA {', '.join(touched)} TO {role};")
    out.append("")
    out.append("-- ownership")
    for role in sorted(roles):
        for name in roles[role]["owns"]:
            kind = "m" if name in caggs else catalog.get(name, "r")
            out.append(f"{OWNER_STMT[kind]} {name} OWNER TO {role};")
    out.append("")
    out.append("-- transition views (owner postgres: evaluated with its rights, independent of RLS)")
    for view, body in VIEWS.items():
        out.append(f"CREATE OR REPLACE VIEW {view} AS {body};")
        out.append(f"ALTER VIEW {view} OWNER TO postgres;")
        for role in module_roles:
            out.append(f"GRANT SELECT ON {view} TO {role};")
    out.append("")
    out.append("-- transition grants (explicit; each one is a future API call)")
    for role in module_roles:
        for name in roles[role]["reads"]:
            if name not in VIEWS:
                out.append(f"GRANT SELECT ON {name} TO {role};")
        for name in roles[role]["writes"]:
            out.append(f"GRANT SELECT, INSERT, UPDATE, DELETE ON {name} TO {role};")
    out.append("")
    out.append("-- future core tables created by migrations (run as postgres) stay reachable")
    out.append(f"ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA {', '.join(core_schemas)} GRANT ALL ON TABLES TO nkz_core;")
    out.append(f"ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA {', '.join(core_schemas)} GRANT ALL ON SEQUENCES TO nkz_core;")
    return "\n".join(out) + "\n"


def _load_catalog(path: str) -> dict:
    cat = {}
    for line in open(path, encoding="utf-8"):
        parts = line.rstrip("\n").split("|")
        if len(parts) >= 2:
            cat[parts[0]] = parts[1]
    return cat


def main(argv: list[str]) -> int:
    import yaml  # local tooling only

    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    data = yaml.safe_load(open(argv[1], encoding="utf-8"))
    data["catalog"] = _load_catalog(argv[2])
    sys.stdout.write(generate(data))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
